-- Migracao reaplicavel para adicionar projetos e seus vinculos.
-- Execute conectado ao banco que ja contem public.funcionarios.
-- Nao recria o banco, nao altera a chave primaria e nao exclui registros.
BEGIN;

DO $$
BEGIN
    IF to_regclass('public.funcionarios') IS NULL THEN
        RAISE EXCEPTION 'A tabela public.funcionarios nao existe.';
    END IF;
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.funcionarios'::regclass
          AND contype = 'p'
          AND pg_get_constraintdef(oid) = 'PRIMARY KEY (eid)'
    ) THEN
        RAISE EXCEPTION 'A chave primaria esperada public.funcionarios(eid) nao foi encontrada.';
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.projetos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL CHECK (btrim(nome) <> ''),
    descricao TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'ativo'
        CHECK (status IN ('ativo', 'inativo')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS projetos_nome_normalizado_uq
    ON public.projetos (lower(btrim(nome)));

CREATE TABLE IF NOT EXISTS public.funcionario_projeto (
    funcionario_id VARCHAR(20) NOT NULL,
    projeto_id BIGINT NOT NULL,
    vinculado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT funcionario_projeto_pkey PRIMARY KEY (funcionario_id, projeto_id),
    CONSTRAINT funcionario_projeto_funcionario_id_fkey
        FOREIGN KEY (funcionario_id) REFERENCES public.funcionarios (eid)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT funcionario_projeto_projeto_id_fkey
        FOREIGN KEY (projeto_id) REFERENCES public.projetos (id)
        ON UPDATE RESTRICT ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS funcionario_projeto_projeto_idx
    ON public.funcionario_projeto (projeto_id);

CREATE OR REPLACE FUNCTION public.atualizar_data_projeto()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.atualizado_em := clock_timestamp();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS projetos_atualizado_em ON public.projetos;
CREATE TRIGGER projetos_atualizado_em
BEFORE UPDATE ON public.projetos
FOR EACH ROW EXECUTE FUNCTION public.atualizar_data_projeto();

COMMIT;
