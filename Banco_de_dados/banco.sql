-- PostgreSQL: execute conectado ao banco sistema_notificacao.
-- O comando `py scripts/banco.py iniciar` cria o banco e aplica este arquivo.
BEGIN;

CREATE TABLE IF NOT EXISTS public.funcionarios (
    eid VARCHAR(20) PRIMARY KEY CHECK (btrim(eid) <> ''),
    nome VARCHAR(150) NOT NULL CHECK (btrim(nome) <> ''),
    torre VARCHAR(100),
    login VARCHAR(100),
    login_elevado VARCHAR(100),
    status VARCHAR(30) NOT NULL DEFAULT 'pendente'
        CHECK (status IN ('ativo', 'inativo', 'pendente', 'bloqueado')),
    nova_expiracao DATE,
    acessos TEXT,
    observacao TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON COLUMN public.funcionarios.login_elevado IS
    'Identificador da conta elevada; nao armazena senhas.';
COMMENT ON COLUMN public.funcionarios.acessos IS
    'Descricao livre dos sistemas ou permissoes de acesso.';
COMMENT ON COLUMN public.funcionarios.nova_expiracao IS
    'Data de expiracao do acesso; NULL quando nao informada.';

CREATE INDEX IF NOT EXISTS funcionarios_expiracao_idx
    ON public.funcionarios (nova_expiracao) WHERE status = 'ativo';

CREATE OR REPLACE FUNCTION public.atualizar_data_funcionario()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.atualizado_em := clock_timestamp();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS funcionarios_atualizado_em ON public.funcionarios;
CREATE TRIGGER funcionarios_atualizado_em
BEFORE UPDATE ON public.funcionarios
FOR EACH ROW EXECUTE FUNCTION public.atualizar_data_funcionario();

-- Projetos sao registros; nao se cria uma tabela fisica para cada projeto.
CREATE TABLE IF NOT EXISTS public.projetos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL CHECK (btrim(nome) <> ''),
    descricao TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'ativo'
        CHECK (status IN ('ativo', 'inativo')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Impede nomes repetidos mesmo com diferencas apenas de maiusculas ou espacos.
CREATE UNIQUE INDEX IF NOT EXISTS projetos_nome_normalizado_uq
    ON public.projetos (lower(btrim(nome)));

CREATE TABLE IF NOT EXISTS public.funcionario_projeto (
    funcionario_id VARCHAR(20) NOT NULL,
    projeto_id BIGINT NOT NULL,
    vinculado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT funcionario_projeto_pkey PRIMARY KEY (funcionario_id, projeto_id),
    CONSTRAINT funcionario_projeto_funcionario_id_fkey
        FOREIGN KEY (funcionario_id) REFERENCES public.funcionarios (eid)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT funcionario_projeto_projeto_id_fkey
        FOREIGN KEY (projeto_id) REFERENCES public.projetos (id)
        ON UPDATE RESTRICT ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS funcionario_projeto_projeto_idx
    ON public.funcionario_projeto (projeto_id);

CREATE OR REPLACE FUNCTION public.atualizar_data_projeto()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.atualizado_em := clock_timestamp();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS projetos_atualizado_em ON public.projetos;
CREATE TRIGGER projetos_atualizado_em
BEFORE UPDATE ON public.projetos
FOR EACH ROW EXECUTE FUNCTION public.atualizar_data_projeto();

-- As nove colunas e os titulos da imagem, na mesma ordem.
CREATE OR REPLACE VIEW public.vw_planilha AS
SELECT nome AS "Nome", eid AS "EID", torre AS "Torre", login AS "Login",
       login_elevado AS "Login Elevado", status AS "Status",
       nova_expiracao AS "Nova expiração", acessos AS "Acessos",
       observacao AS "Observação"
FROM public.funcionarios;

COMMIT;
