const { test } = require('node:test');
const assert = require('node:assert/strict');
const { once } = require('node:events');
const { pool } = require('../src/config/database');
const { createApp } = require('../src/app');

async function serve(db) {
  const server = createApp(db).listen(0, '127.0.0.1');
  await once(server, 'listening');
  return {
    base: `http://127.0.0.1:${server.address().port}`,
    close: () => new Promise((resolve, reject) => {
      server.close((error) => error ? reject(error) : resolve());
      server.closeAllConnections();
    }),
  };
}

async function json(base, route, method = 'GET', body) {
  const response = await fetch(base + route, {
    method,
    headers: body === undefined ? {} : { 'Content-Type': 'application/json' },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  return { response, data: response.status === 204 ? null : await response.json() };
}

test('Projetos e vinculos usam tabelas temporarias sem alterar dados reais', { timeout: 30000 }, async (t) => {
  const client = await pool.connect();
  let app;
  try {
    await client.query('CREATE TEMP TABLE funcionarios (LIKE public.funcionarios INCLUDING ALL)');
    await client.query(`
      CREATE TEMP TABLE projetos (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome VARCHAR(150) NOT NULL CHECK (btrim(nome) <> ''),
        descricao TEXT,
        status VARCHAR(20) NOT NULL DEFAULT 'ativo' CHECK (status IN ('ativo', 'inativo')),
        criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query('CREATE UNIQUE INDEX projetos_nome_normalizado_uq ON projetos (lower(btrim(nome)))');
    await client.query(`
      CREATE TEMP TABLE funcionario_projeto (
        funcionario_id VARCHAR(20) NOT NULL REFERENCES funcionarios(eid) ON DELETE RESTRICT,
        projeto_id BIGINT NOT NULL REFERENCES projetos(id) ON DELETE CASCADE,
        vinculado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT funcionario_projeto_pkey PRIMARY KEY (funcionario_id, projeto_id)
      )
    `);
    await client.query(`
      INSERT INTO funcionarios (eid, nome, status)
      VALUES ('TST001', 'Ana Teste', 'ativo'), ('TST002', 'Bruno Teste', 'pendente')
    `);
    const db = {
      query(text, values) {
        return client.query(text
          .replaceAll('public.funcionario_projeto', 'pg_temp.funcionario_projeto')
          .replaceAll('public.funcionarios', 'pg_temp.funcionarios')
          .replaceAll('public.projetos', 'pg_temp.projetos'), values);
      },
    };
    app = await serve(db);
    let projectId;

    await t.test('cria projeto e impede nome duplicado sem diferenciar maiusculas', async () => {
      const created = await json(app.base, '/api/projetos', 'POST', {
        nome: 'Projeto Alpha', descricao: 'Equipe de teste', status: 'ativo',
      });
      assert.equal(created.response.status, 201);
      projectId = created.data.id;
      assert.equal(created.data.total_funcionarios, 0);
      const duplicate = await json(app.base, '/api/projetos', 'POST', {
        nome: '  projeto alpha  ', status: 'ativo',
      });
      assert.equal(duplicate.response.status, 409);
      assert.equal(duplicate.data.error.code, 'PROJECT_NAME_CONFLICT');
    });

    await t.test('lista projeto com total inicial zerado', async () => {
      const { response, data } = await json(app.base, '/api/projetos');
      assert.equal(response.status, 200);
      assert.equal(data.length, 1);
      assert.equal(data[0].total_funcionarios, 0);
    });

    await t.test('vincula varios funcionarios e ignora repeticao', async () => {
      const first = await json(app.base, `/api/projetos/${projectId}/funcionarios`, 'POST', {
        funcionario_ids: ['TST001', 'TST002'],
      });
      assert.equal(first.response.status, 201);
      assert.deepEqual(first.data.adicionados.sort(), ['TST001', 'TST002']);
      const repeated = await json(app.base, `/api/projetos/${projectId}/funcionarios`, 'POST', {
        funcionario_ids: ['TST001'],
      });
      assert.equal(repeated.response.status, 201);
      assert.deepEqual(repeated.data.adicionados, []);
      assert.deepEqual(repeated.data.ja_vinculados, ['TST001']);
    });

    await t.test('consulta a equipe do projeto e os projetos do funcionario', async () => {
      const team = await json(app.base, `/api/projetos/${projectId}/funcionarios`);
      assert.equal(team.response.status, 200);
      assert.deepEqual(team.data.map((person) => person.eid), ['TST001', 'TST002']);
      const projects = await json(app.base, '/api/funcionarios/TST001/projetos');
      assert.equal(projects.response.status, 200);
      assert.equal(projects.data[0].nome, 'Projeto Alpha');
    });

    await t.test('rejeita vinculo com funcionario inexistente', async () => {
      const { response, data } = await json(app.base, `/api/projetos/${projectId}/funcionarios`, 'POST', {
        funcionario_ids: ['NAO_EXISTE'],
      });
      assert.equal(response.status, 400);
      assert.equal(data.error.code, 'EMPLOYEE_NOT_FOUND');
    });

    await t.test('remove somente o vinculo e preserva o funcionario', async () => {
      const removed = await json(app.base, `/api/projetos/${projectId}/funcionarios/TST001`, 'DELETE');
      assert.equal(removed.response.status, 204);
      const employee = await client.query("SELECT nome FROM pg_temp.funcionarios WHERE eid = 'TST001'");
      assert.equal(employee.rows[0].nome, 'Ana Teste');
      const links = await client.query("SELECT count(*)::int total FROM pg_temp.funcionario_projeto WHERE funcionario_id = 'TST001'");
      assert.equal(links.rows[0].total, 0);
    });

    await t.test('edita e exclui projeto sem excluir funcionarios', async () => {
      const updated = await json(app.base, `/api/projetos/${projectId}`, 'PUT', { status: 'inativo' });
      assert.equal(updated.response.status, 200);
      assert.equal(updated.data.status, 'inativo');
      const removed = await json(app.base, `/api/projetos/${projectId}`, 'DELETE');
      assert.equal(removed.response.status, 204);
      const employees = await client.query('SELECT count(*)::int total FROM pg_temp.funcionarios');
      assert.equal(employees.rows[0].total, 2);
      const links = await client.query('SELECT count(*)::int total FROM pg_temp.funcionario_projeto');
      assert.equal(links.rows[0].total, 0);
    });
  } finally {
    if (app) await app.close();
    client.release();
    await pool.end();
  }
});
